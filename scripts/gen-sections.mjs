// Regenerates src/app/articles/personal-finance-india/sections.js — the per-chapter
// mini-index rendered by <ChapterIndex>.
//
//   node scripts/gen-sections.mjs
//
// Run this whenever a chapter's `##` headings change, or the index will drift
// from the page. It is deliberately NOT a prebuild hook: `npm run build` must
// not rewrite tracked source files behind your back.
//
// Slug parity is the whole trick. next.config.mjs runs rehype-slug over the MDX,
// which walks *every* heading (h1..h6) in document order with one GithubSlugger
// per file, deduping collisions as `-1`, `-2`. This replays that exact sequence
// and then keeps only the h2 entries, so the hrefs match the ids rehype-slug
// emits even when an h3 collides with an h2.

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import GithubSlugger from 'github-slugger'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHAPTERS_DIR = join(ROOT, 'src/app/articles/personal-finance-india')
const OUT = join(CHAPTERS_DIR, 'sections.js')

/** Strip the inline markdown rehype-slug would have resolved before slugging. */
function toText(markdown) {
  return markdown
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/(\*\*|__)(.*?)\1/g, '$2')
    .replace(/(\*|_)(.*?)\1/g, '$2')
    .trim()
}

/** A leading "7.5 " / "10.  " is the chapter number — split it out so the
 *  component can render it in a fixed-width gutter like the sidebar does. */
function splitNumber(text) {
  const match = /^(\d+(?:\.\d+)*)\s+(.*)$/.exec(text)
  return match ? { n: match[1], label: match[2] } : { n: null, label: text }
}

function sectionsFor(mdx) {
  const slugger = new GithubSlugger()
  const sections = []

  let inFence = false
  for (const line of mdx.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence
      continue
    }
    if (inFence) continue

    const heading = /^(#{1,6})\s+(.*)$/.exec(line)
    if (!heading) continue

    const text = toText(heading[2])
    const id = slugger.slug(text) // consumes a slug for EVERY heading level
    if (heading[1].length !== 2) continue

    sections.push({ id, ...splitNumber(text) })
  }

  return sections
}

const slugs = readdirSync(CHAPTERS_DIR)
  .filter((entry) => statSync(join(CHAPTERS_DIR, entry)).isDirectory())
  .sort()

const entries = []
for (const slug of slugs) {
  let mdx
  try {
    mdx = readFileSync(join(CHAPTERS_DIR, slug, 'page.mdx'), 'utf8')
  } catch {
    continue // e.g. /calculator, which is a .jsx page with no MDX headings
  }
  const sections = sectionsFor(mdx)
  if (sections.length) entries.push([slug, sections])
}

const body = entries
  .map(
    ([slug, sections]) =>
      `  '${slug}': [\n` +
      sections
        .map(
          (s) =>
            `    { n: ${s.n === null ? 'null' : `'${s.n}'`}, ` +
            `label: ${JSON.stringify(s.label)}, id: '${s.id}' },`,
        )
        .join('\n') +
      `\n  ],`,
  )
  .join('\n')

writeFileSync(
  OUT,
  `// Generated by scripts/gen-sections.mjs — do not edit by hand.\n` +
    `// Re-run \`node scripts/gen-sections.mjs\` after changing any chapter's \`##\` headings.\n` +
    `// Keyed by chapter directory; \`id\` matches the anchor rehype-slug puts on the heading.\n` +
    `export const sections = {\n${body}\n}\n`,
  'utf8',
)

console.log(
  `wrote ${OUT} — ${entries.length} chapters, ` +
    `${entries.reduce((total, [, s]) => total + s.length, 0)} sections`,
)
